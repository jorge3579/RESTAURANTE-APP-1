CREATE TABLE IF NOT EXISTS comandas
(
    id_comanda BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pedido BIGINT
        NOT NULL,

    id_sucursal INTEGER
        NOT NULL,

    numero_comanda VARCHAR(50),

    prioridad VARCHAR(20)
        NOT NULL
        DEFAULT 'NORMAL',

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    tiempo_estimado_minutos INTEGER,

    observaciones VARCHAR(1000),

    fecha_recepcion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_inicio TIMESTAMPTZ,

    fecha_lista TIMESTAMPTZ,

    fecha_entrega TIMESTAMPTZ,

    fecha_cancelacion TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_comandas_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_comandas_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_comandas_numero
        UNIQUE (numero_comanda),

    CONSTRAINT ck_comandas_prioridad
        CHECK
        (
            prioridad IN
            (
                'BAJA',
                'NORMAL',
                'ALTA',
                'URGENTE'
            )
        ),

    CONSTRAINT ck_comandas_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'EN_PREPARACION',
                'LISTA',
                'ENTREGADA',
                'CANCELADA'
            )
        ),

    CONSTRAINT ck_comandas_tiempo
        CHECK
        (
            tiempo_estimado_minutos IS NULL
            OR tiempo_estimado_minutos
                BETWEEN 1 AND 300
        )
);


CREATE TABLE IF NOT EXISTS comanda_detalles
(
    id_comanda_detalle BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_comanda BIGINT
        NOT NULL,

    id_pedido_detalle BIGINT
        NOT NULL,

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    observaciones VARCHAR(500),

    fecha_inicio TIMESTAMPTZ,

    fecha_finalizacion TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_comanda_detalles_comanda
        FOREIGN KEY (id_comanda)
        REFERENCES comandas(id_comanda)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_comanda_detalles_pedido_detalle
        FOREIGN KEY (id_pedido_detalle)
        REFERENCES pedido_detalles(id_pedido_detalle)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_comanda_detalles
        UNIQUE
        (
            id_comanda,
            id_pedido_detalle
        ),

    CONSTRAINT ck_comanda_detalles_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'EN_PREPARACION',
                'LISTO',
                'ENTREGADO',
                'CANCELADO'
            )
        )
);


CREATE TABLE IF NOT EXISTS historial_comandas
(
    id_historial_comanda BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_comanda BIGINT
        NOT NULL,

    id_usuario INTEGER,

    estado_anterior VARCHAR(30),

    estado_nuevo VARCHAR(30)
        NOT NULL,

    observaciones VARCHAR(500),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_historial_comandas_comanda
        FOREIGN KEY (id_comanda)
        REFERENCES comandas(id_comanda)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_historial_comandas_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


CREATE TABLE IF NOT EXISTS impresiones_comanda
(
    id_impresion BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_comanda BIGINT
        NOT NULL,

    tipo VARCHAR(30)
        NOT NULL,

    impresora VARCHAR(150),

    copias INTEGER
        NOT NULL
        DEFAULT 1,

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    contenido TEXT,

    fecha_impresion TIMESTAMPTZ,

    mensaje_error TEXT,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_impresiones_comanda
        FOREIGN KEY (id_comanda)
        REFERENCES comandas(id_comanda)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT ck_impresiones_comanda_tipo
        CHECK
        (
            tipo IN
            (
                'COCINA',
                'BARRA',
                'CAJA',
                'CLIENTE'
            )
        ),

    CONSTRAINT ck_impresiones_comanda_copias
        CHECK
        (
            copias BETWEEN 1 AND 10
        ),

    CONSTRAINT ck_impresiones_comanda_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'ENVIADA',
                'IMPRESA',
                'ERROR',
                'CANCELADA'
            )
        )
);


CREATE INDEX IF NOT EXISTS
    ix_comandas_id_pedido
ON comandas(id_pedido);


CREATE INDEX IF NOT EXISTS
    ix_comandas_sucursal_estado
ON comandas
(
    id_sucursal,
    estado,
    fecha_creacion
);


CREATE INDEX IF NOT EXISTS
    ix_comandas_pendientes
ON comandas
(
    id_sucursal,
    prioridad,
    fecha_creacion
)
WHERE estado IN
(
    'PENDIENTE',
    'EN_PREPARACION'
);


CREATE INDEX IF NOT EXISTS
    ix_comanda_detalles_id_comanda
ON comanda_detalles(id_comanda);


CREATE INDEX IF NOT EXISTS
    ix_comanda_detalles_estado
ON comanda_detalles(estado);


CREATE INDEX IF NOT EXISTS
    ix_historial_comandas_id_comanda
ON historial_comandas
(
    id_comanda,
    fecha_creacion DESC
);


CREATE INDEX IF NOT EXISTS
    ix_impresiones_comanda_pendientes
ON impresiones_comanda(fecha_creacion)
WHERE estado = 'PENDIENTE';


COMMENT ON TABLE comandas IS
    'Órdenes enviadas a cocina o barra.';

COMMENT ON TABLE comanda_detalles IS
    'Productos incluidos en una comanda.';

COMMENT ON TABLE impresiones_comanda IS
    'Trabajos de impresión asociados a las comandas.';