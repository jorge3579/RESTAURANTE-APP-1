CREATE TABLE IF NOT EXISTS promociones
(
    id_promocion INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_sucursal INTEGER,

    nombre VARCHAR(150)
        NOT NULL,

    descripcion VARCHAR(1000),

    codigo VARCHAR(50),

    tipo VARCHAR(40)
        NOT NULL,

    valor NUMERIC(14, 2)
        NOT NULL,

    monto_minimo NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    cantidad_minima INTEGER,

    fecha_inicio TIMESTAMPTZ
        NOT NULL,

    fecha_fin TIMESTAMPTZ
        NOT NULL,

    hora_inicio TIME,

    hora_fin TIME,

    dias_semana SMALLINT[],

    limite_total_usos INTEGER,

    limite_usos_usuario INTEGER,

    acumulable BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    requiere_codigo BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    activa BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_promociones_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_promociones_codigo
        UNIQUE (codigo),

    CONSTRAINT ck_promociones_tipo
        CHECK
        (
            tipo IN
            (
                'PORCENTAJE',
                'MONTO_FIJO',
                'PRODUCTO_GRATIS',
                'DOS_POR_UNO',
                'ENVIO_GRATIS',
                'PREMIO_FIDELIZACION'
            )
        ),

    CONSTRAINT ck_promociones_valor
        CHECK (valor >= 0),

    CONSTRAINT ck_promociones_monto_minimo
        CHECK (monto_minimo >= 0),

    CONSTRAINT ck_promociones_cantidad_minima
        CHECK
        (
            cantidad_minima IS NULL
            OR cantidad_minima > 0
        ),

    CONSTRAINT ck_promociones_fechas
        CHECK (fecha_fin > fecha_inicio),

    CONSTRAINT ck_promociones_limite_total
        CHECK
        (
            limite_total_usos IS NULL
            OR limite_total_usos > 0
        ),

    CONSTRAINT ck_promociones_limite_usuario
        CHECK
        (
            limite_usos_usuario IS NULL
            OR limite_usos_usuario > 0
        ),

    CONSTRAINT ck_promociones_porcentaje
        CHECK
        (
            tipo <> 'PORCENTAJE'
            OR valor BETWEEN 0 AND 100
        )
);


CREATE TABLE IF NOT EXISTS promocion_productos
(
    id_promocion_producto BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_promocion INTEGER
        NOT NULL,

    id_producto INTEGER
        NOT NULL,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_promocion_productos_promocion
        FOREIGN KEY (id_promocion)
        REFERENCES promociones(id_promocion)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_promocion_productos_producto
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_promocion_productos
        UNIQUE (id_promocion, id_producto)
);


CREATE TABLE IF NOT EXISTS promocion_categorias
(
    id_promocion_categoria BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_promocion INTEGER
        NOT NULL,

    id_categoria INTEGER
        NOT NULL,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_promocion_categorias_promocion
        FOREIGN KEY (id_promocion)
        REFERENCES promociones(id_promocion)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_promocion_categorias_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categorias(id_categoria)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_promocion_categorias
        UNIQUE (id_promocion, id_categoria)
);


CREATE TABLE IF NOT EXISTS beneficios_aplicados
(
    id_beneficio_aplicado BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_pedido BIGINT
        NOT NULL,

    id_promocion INTEGER,

    tipo_beneficio VARCHAR(40)
        NOT NULL,

    descripcion VARCHAR(500),

    monto_original NUMERIC(14, 2)
        NOT NULL,

    monto_beneficio NUMERIC(14, 2)
        NOT NULL,

    monto_final NUMERIC(14, 2)
        NOT NULL,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_beneficios_aplicados_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_beneficios_aplicados_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_beneficios_aplicados_promocion
        FOREIGN KEY (id_promocion)
        REFERENCES promociones(id_promocion)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_beneficios_aplicados_tipo
        CHECK
        (
            tipo_beneficio IN
            (
                'PROMOCION',
                'DESCUENTO_VIP',
                'PREMIO',
                'CREDITO'
            )
        ),

    CONSTRAINT ck_beneficios_aplicados_montos
        CHECK
        (
            monto_original >= 0
            AND monto_beneficio >= 0
            AND monto_final >= 0
            AND monto_final =
                monto_original - monto_beneficio
        )
);


CREATE INDEX IF NOT EXISTS
    ix_promociones_id_sucursal
ON promociones(id_sucursal);


CREATE INDEX IF NOT EXISTS
    ix_promociones_vigencia
ON promociones(fecha_inicio, fecha_fin);


CREATE INDEX IF NOT EXISTS
    ix_promociones_activas
ON promociones(fecha_inicio, fecha_fin)
WHERE activa = TRUE;


CREATE INDEX IF NOT EXISTS
    ix_promocion_productos_id_producto
ON promocion_productos(id_producto);


CREATE INDEX IF NOT EXISTS
    ix_promocion_categorias_id_categoria
ON promocion_categorias(id_categoria);


CREATE INDEX IF NOT EXISTS
    ix_beneficios_aplicados_usuario
ON beneficios_aplicados(id_usuario, fecha_creacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_beneficios_aplicados_pedido
ON beneficios_aplicados(id_pedido);


COMMENT ON TABLE promociones IS
    'Promociones configurables por fechas, sucursal, productos o categorías.';

COMMENT ON TABLE beneficios_aplicados IS
    'Historial de descuentos, promociones, premios y créditos aplicados.';