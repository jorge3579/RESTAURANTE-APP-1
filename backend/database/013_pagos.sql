CREATE TABLE IF NOT EXISTS pagos
(
    id_pago BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pedido BIGINT
        NOT NULL,

    id_usuario INTEGER
        NOT NULL,

    metodo_pago VARCHAR(50)
        NOT NULL,

    proveedor VARCHAR(100),

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    moneda VARCHAR(10)
        NOT NULL
        DEFAULT 'ARS',

    monto NUMERIC(14, 2)
        NOT NULL,

    referencia_externa VARCHAR(255),

    identificador_proveedor VARCHAR(255),

    detalle_estado VARCHAR(255),

    payload_respuesta JSONB,

    fecha_aprobacion TIMESTAMPTZ,

    fecha_rechazo TIMESTAMPTZ,

    fecha_cancelacion TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_pagos_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pagos_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_pagos_metodo
        CHECK
        (
            metodo_pago IN
            (
                'EFECTIVO',
                'MERCADO_PAGO',
                'PAYWAY',
                'TARJETA_CREDITO',
                'TARJETA_DEBITO',
                'TRANSFERENCIA',
                'CREDITO_USUARIO'
            )
        ),

    CONSTRAINT ck_pagos_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'EN_PROCESO',
                'APROBADO',
                'RECHAZADO',
                'CANCELADO',
                'DEVUELTO',
                'DEVUELTO_PARCIAL'
            )
        ),

    CONSTRAINT ck_pagos_monto
        CHECK (monto > 0),

    CONSTRAINT ck_pagos_moneda
        CHECK (LENGTH(TRIM(moneda)) = 3)
);


CREATE TABLE IF NOT EXISTS devoluciones_pago
(
    id_devolucion_pago BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pago BIGINT
        NOT NULL,

    id_usuario INTEGER,

    monto NUMERIC(14, 2)
        NOT NULL,

    motivo VARCHAR(500)
        NOT NULL,

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    identificador_proveedor VARCHAR(255),

    payload_respuesta JSONB,

    fecha_procesamiento TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_devoluciones_pago_pago
        FOREIGN KEY (id_pago)
        REFERENCES pagos(id_pago)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_devoluciones_pago_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_devoluciones_pago_monto
        CHECK (monto > 0),

    CONSTRAINT ck_devoluciones_pago_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'EN_PROCESO',
                'APROBADA',
                'RECHAZADA',
                'CANCELADA'
            )
        )
);


CREATE INDEX IF NOT EXISTS
    ix_pagos_id_pedido
ON pagos(id_pedido);


CREATE INDEX IF NOT EXISTS
    ix_pagos_id_usuario
ON pagos(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_pagos_estado
ON pagos(estado);


CREATE INDEX IF NOT EXISTS
    ix_pagos_metodo
ON pagos(metodo_pago);


CREATE INDEX IF NOT EXISTS
    ix_pagos_referencia_externa
ON pagos(referencia_externa);


CREATE UNIQUE INDEX IF NOT EXISTS
    uq_pagos_identificador_proveedor
ON pagos(proveedor, identificador_proveedor)
WHERE identificador_proveedor IS NOT NULL;


CREATE INDEX IF NOT EXISTS
    ix_pagos_fecha_creacion
ON pagos(fecha_creacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_devoluciones_pago_id_pago
ON devoluciones_pago(id_pago);


CREATE INDEX IF NOT EXISTS
    ix_devoluciones_pago_estado
ON devoluciones_pago(estado);


COMMENT ON TABLE pagos IS
    'Pagos realizados mediante efectivo, Mercado Pago, Payway u otros medios.';

COMMENT ON TABLE devoluciones_pago IS
    'Devoluciones totales o parciales asociadas a pagos.';