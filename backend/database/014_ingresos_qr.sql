CREATE TABLE IF NOT EXISTS ingresos_qr
(
    id_ingreso_qr BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_reserva BIGINT
        NOT NULL,

    codigo_qr UUID
        NOT NULL
        DEFAULT gen_random_uuid(),

    contenido_qr TEXT,

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'ACTIVO',

    fecha_generacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_expiracion TIMESTAMPTZ,

    fecha_utilizacion TIMESTAMPTZ,

    validado_por INTEGER,

    dispositivo_validacion VARCHAR(255),

    ip_validacion VARCHAR(50),

    observaciones VARCHAR(500),

    CONSTRAINT fk_ingresos_qr_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES reservas(id_reserva)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_ingresos_qr_usuario_validacion
        FOREIGN KEY (validado_por)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT uq_ingresos_qr_codigo
        UNIQUE (codigo_qr),

    CONSTRAINT ck_ingresos_qr_estado
        CHECK
        (
            estado IN
            (
                'ACTIVO',
                'UTILIZADO',
                'VENCIDO',
                'CANCELADO',
                'BLOQUEADO'
            )
        ),

    CONSTRAINT ck_ingresos_qr_expiracion
        CHECK
        (
            fecha_expiracion IS NULL
            OR fecha_expiracion > fecha_generacion
        )
);


/*
Historial de intentos de validación.

Registra tanto ingresos válidos como intentos inválidos.
*/

CREATE TABLE IF NOT EXISTS validaciones_qr
(
    id_validacion_qr BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_ingreso_qr BIGINT,

    codigo_ingresado VARCHAR(255),

    id_usuario_validador INTEGER,

    resultado VARCHAR(30)
        NOT NULL,

    mensaje VARCHAR(500),

    dispositivo VARCHAR(255),

    ip VARCHAR(50),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_validaciones_qr_ingreso
        FOREIGN KEY (id_ingreso_qr)
        REFERENCES ingresos_qr(id_ingreso_qr)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_validaciones_qr_usuario
        FOREIGN KEY (id_usuario_validador)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_validaciones_qr_resultado
        CHECK
        (
            resultado IN
            (
                'VALIDO',
                'INVALIDO',
                'UTILIZADO',
                'VENCIDO',
                'CANCELADO',
                'NO_ENCONTRADO'
            )
        )
);


CREATE INDEX IF NOT EXISTS
    ix_ingresos_qr_id_reserva
ON ingresos_qr(id_reserva);


CREATE INDEX IF NOT EXISTS
    ix_ingresos_qr_estado
ON ingresos_qr(estado);


CREATE INDEX IF NOT EXISTS
    ix_ingresos_qr_activos
ON ingresos_qr(codigo_qr, fecha_expiracion)
WHERE estado = 'ACTIVO';


CREATE INDEX IF NOT EXISTS
    ix_validaciones_qr_id_ingreso
ON validaciones_qr(id_ingreso_qr);


CREATE INDEX IF NOT EXISTS
    ix_validaciones_qr_fecha
ON validaciones_qr(fecha_creacion DESC);


COMMENT ON TABLE ingresos_qr IS
    'Códigos QR generados para validar el ingreso de una reserva.';

COMMENT ON TABLE validaciones_qr IS
    'Historial de validaciones e intentos de uso de códigos QR.';