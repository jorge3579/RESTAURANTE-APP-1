CREATE TABLE IF NOT EXISTS roles
(
    id_rol INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(50)
        NOT NULL,

    descripcion VARCHAR(255),

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_roles_nombre
        UNIQUE (nombre)
);


CREATE TABLE IF NOT EXISTS permisos
(
    id_permiso INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    codigo VARCHAR(100)
        NOT NULL,

    nombre VARCHAR(100)
        NOT NULL,

    descripcion VARCHAR(255),

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_permisos_codigo
        UNIQUE (codigo)
);


CREATE TABLE IF NOT EXISTS rol_permisos
(
    id_rol_permiso BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_rol INTEGER
        NOT NULL,

    id_permiso INTEGER
        NOT NULL,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_rol_permisos_rol
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_rol_permisos_permiso
        FOREIGN KEY (id_permiso)
        REFERENCES permisos(id_permiso)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_rol_permisos
        UNIQUE (id_rol, id_permiso)
);


CREATE INDEX IF NOT EXISTS
    ix_rol_permisos_id_rol
ON rol_permisos(id_rol);


CREATE INDEX IF NOT EXISTS
    ix_rol_permisos_id_permiso
ON rol_permisos(id_permiso);


COMMENT ON TABLE roles IS
    'Roles disponibles para usuarios y empleados del sistema.';

COMMENT ON TABLE permisos IS
    'Acciones autorizables dentro de SmartRestaurantQR.';

COMMENT ON TABLE rol_permisos IS
    'Relación entre roles y permisos.';