CREATE TABLE IF NOT EXISTS sucursales
(
    id_sucursal INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(150)
        NOT NULL,

    descripcion VARCHAR(500),

    direccion VARCHAR(255)
        NOT NULL,

    ciudad VARCHAR(100)
        NOT NULL
        DEFAULT 'Bahía Blanca',

    provincia VARCHAR(100)
        NOT NULL
        DEFAULT 'Buenos Aires',

    codigo_postal VARCHAR(20),

    telefono VARCHAR(50),

    email CITEXT,

    latitud NUMERIC(10, 7),

    longitud NUMERIC(10, 7),

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_sucursales_nombre
        UNIQUE (nombre),

    CONSTRAINT uq_sucursales_email
        UNIQUE (email),

    CONSTRAINT ck_sucursales_nombre
        CHECK (LENGTH(TRIM(nombre)) >= 2),

    CONSTRAINT ck_sucursales_latitud
        CHECK
        (
            latitud IS NULL
            OR latitud BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_sucursales_longitud
        CHECK
        (
            longitud IS NULL
            OR longitud BETWEEN -180 AND 180
        )
);


CREATE TABLE IF NOT EXISTS horarios_sucursal
(
    id_horario_sucursal INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_sucursal INTEGER
        NOT NULL,

    dia_semana SMALLINT
        NOT NULL,

    hora_apertura TIME,

    hora_cierre TIME,

    cerrado BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_horarios_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT ck_horarios_dia_semana
        CHECK (dia_semana BETWEEN 1 AND 7),

    CONSTRAINT ck_horarios_horas
        CHECK
        (
            cerrado = TRUE
            OR
            (
                hora_apertura IS NOT NULL
                AND hora_cierre IS NOT NULL
                AND hora_apertura <> hora_cierre
            )
        ),

    CONSTRAINT uq_horarios_sucursal_dia
        UNIQUE (id_sucursal, dia_semana)
);


CREATE INDEX IF NOT EXISTS
    ix_sucursales_activo
ON sucursales(activo);


CREATE INDEX IF NOT EXISTS
    ix_sucursales_ciudad
ON sucursales(ciudad);


CREATE INDEX IF NOT EXISTS
    ix_horarios_sucursal_id_sucursal
ON horarios_sucursal(id_sucursal);


COMMENT ON TABLE sucursales IS
    'Locales físicos administrados por SmartRestaurantQR.';

COMMENT ON TABLE horarios_sucursal IS
    'Horarios de apertura y cierre por día de cada sucursal.';

COMMENT ON COLUMN horarios_sucursal.dia_semana IS
    '1 lunes, 2 martes, 3 miércoles, 4 jueves, 5 viernes, 6 sábado, 7 domingo.';