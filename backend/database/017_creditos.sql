CREATE TABLE IF NOT EXISTS creditos_usuario
(
    id_credito BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_reserva_origen BIGINT,

    id_pedido_origen BIGINT,

    monto_original NUMERIC(14, 2)
        NOT NULL,

    saldo_disponible NUMERIC(14, 2)
        NOT NULL,

    motivo VARCHAR(500)
        NOT NULL,

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'ACTIVO',

    fecha_vencimiento TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_creditos_usuario_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_creditos_usuario_reserva
        FOREIGN KEY (id_reserva_origen)
        REFERENCES reservas(id_reserva)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_creditos_usuario_pedido
        FOREIGN KEY (id_pedido_origen)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_creditos_usuario_monto_original
        CHECK (monto_original > 0),

    CONSTRAINT ck_creditos_usuario_saldo
        CHECK
        (
            saldo_disponible >= 0
            AND saldo_disponible <= monto_original
        ),

    CONSTRAINT ck_creditos_usuario_estado
        CHECK
        (
            estado IN
            (
                'ACTIVO',
                'CONSUMIDO',
                'VENCIDO',
                'CANCELADO'
            )
        )
);


CREATE TABLE IF NOT EXISTS movimientos_credito
(
    id_movimiento_credito BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_credito BIGINT
        NOT NULL,

    id_usuario INTEGER
        NOT NULL,

    id_pedido BIGINT,

    tipo_movimiento VARCHAR(30)
        NOT NULL,

    monto NUMERIC(14, 2)
        NOT NULL,

    saldo_anterior NUMERIC(14, 2)
        NOT NULL,

    saldo_posterior NUMERIC(14, 2)
        NOT NULL,

    descripcion VARCHAR(500),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_movimientos_credito_credito
        FOREIGN KEY (id_credito)
        REFERENCES creditos_usuario(id_credito)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_movimientos_credito_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimientos_credito_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_movimientos_credito_tipo
        CHECK
        (
            tipo_movimiento IN
            (
                'ALTA',
                'CONSUMO',
                'REINTEGRO',
                'AJUSTE_POSITIVO',
                'AJUSTE_NEGATIVO',
                'VENCIMIENTO',
                'CANCELACION'
            )
        ),

    CONSTRAINT ck_movimientos_credito_monto
        CHECK (monto > 0),

    CONSTRAINT ck_movimientos_credito_saldos
        CHECK
        (
            saldo_anterior >= 0
            AND saldo_posterior >= 0
        )
);


CREATE INDEX IF NOT EXISTS
    ix_creditos_usuario_id_usuario
ON creditos_usuario(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_creditos_usuario_activos
ON creditos_usuario(id_usuario, fecha_creacion)
WHERE estado = 'ACTIVO'
  AND saldo_disponible > 0;


CREATE INDEX IF NOT EXISTS
    ix_creditos_usuario_vencimiento
ON creditos_usuario(fecha_vencimiento)
WHERE estado = 'ACTIVO'
  AND fecha_vencimiento IS NOT NULL;


CREATE INDEX IF NOT EXISTS
    ix_movimientos_credito_id_credito
ON movimientos_credito(id_credito, fecha_creacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_movimientos_credito_id_usuario
ON movimientos_credito(id_usuario, fecha_creacion DESC);


COMMENT ON TABLE creditos_usuario IS
    'Créditos generados por cancelaciones, reintegros o ajustes.';

COMMENT ON TABLE movimientos_credito IS
    'Historial completo de movimientos de cada crédito.';