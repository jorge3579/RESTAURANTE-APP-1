CREATE TABLE IF NOT EXISTS dispositivos_push
(
    id_dispositivo_push BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    token_dispositivo TEXT
        NOT NULL,

    plataforma VARCHAR(20)
        NOT NULL,

    nombre_dispositivo VARCHAR(150),

    modelo_dispositivo VARCHAR(150),

    version_sistema VARCHAR(50),

    version_aplicacion VARCHAR(50),

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_ultimo_uso TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_dispositivos_push_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_dispositivos_push_token
        UNIQUE (token_dispositivo),

    CONSTRAINT ck_dispositivos_push_plataforma
        CHECK
        (
            plataforma IN
            (
                'ANDROID',
                'IOS',
                'WEB'
            )
        )
);


CREATE TABLE IF NOT EXISTS notificaciones
(
    id_notificacion BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    titulo VARCHAR(200)
        NOT NULL,

    mensaje TEXT
        NOT NULL,

    tipo VARCHAR(50)
        NOT NULL,

    referencia_tipo VARCHAR(50),

    referencia_id BIGINT,

    datos_adicionales JSONB,

    canal VARCHAR(30)
        NOT NULL
        DEFAULT 'APP',

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    leida BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    fecha_programada TIMESTAMPTZ,

    fecha_envio TIMESTAMPTZ,

    fecha_lectura TIMESTAMPTZ,

    fecha_error TIMESTAMPTZ,

    mensaje_error TEXT,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_notificaciones_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT ck_notificaciones_tipo
        CHECK
        (
            tipo IN
            (
                'SISTEMA',
                'RESERVA',
                'PEDIDO',
                'PAGO',
                'QR',
                'PROMOCION',
                'FIDELIZACION',
                'CREDITO',
                'SEGURIDAD'
            )
        ),

    CONSTRAINT ck_notificaciones_canal
        CHECK
        (
            canal IN
            (
                'APP',
                'PUSH',
                'EMAIL',
                'SMS'
            )
        ),

    CONSTRAINT ck_notificaciones_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'ENVIADA',
                'ERROR',
                'CANCELADA'
            )
        )
);


CREATE TABLE IF NOT EXISTS notificacion_dispositivos
(
    id_notificacion_dispositivo BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_notificacion BIGINT
        NOT NULL,

    id_dispositivo_push BIGINT
        NOT NULL,

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    identificador_envio VARCHAR(255),

    respuesta_proveedor JSONB,

    fecha_envio TIMESTAMPTZ,

    fecha_error TIMESTAMPTZ,

    mensaje_error TEXT,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notificacion_dispositivos_notificacion
        FOREIGN KEY (id_notificacion)
        REFERENCES notificaciones(id_notificacion)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_notificacion_dispositivos_dispositivo
        FOREIGN KEY (id_dispositivo_push)
        REFERENCES dispositivos_push(id_dispositivo_push)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_notificacion_dispositivos
        UNIQUE
        (
            id_notificacion,
            id_dispositivo_push
        ),

    CONSTRAINT ck_notificacion_dispositivos_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'ENVIADA',
                'ERROR'
            )
        )
);


CREATE INDEX IF NOT EXISTS
    ix_dispositivos_push_id_usuario
ON dispositivos_push(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_dispositivos_push_activos
ON dispositivos_push(id_usuario)
WHERE activo = TRUE;


CREATE INDEX IF NOT EXISTS
    ix_notificaciones_id_usuario
ON notificaciones(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_notificaciones_usuario_fecha
ON notificaciones
(
    id_usuario,
    fecha_creacion DESC
);


CREATE INDEX IF NOT EXISTS
    ix_notificaciones_no_leidas
ON notificaciones
(
    id_usuario,
    fecha_creacion DESC
)
WHERE leida = FALSE;


CREATE INDEX IF NOT EXISTS
    ix_notificaciones_pendientes
ON notificaciones
(
    fecha_programada,
    fecha_creacion
)
WHERE estado = 'PENDIENTE';


CREATE INDEX IF NOT EXISTS
    ix_notificacion_dispositivos_estado
ON notificacion_dispositivos(estado);


COMMENT ON TABLE dispositivos_push IS
    'Dispositivos registrados para enviar notificaciones push.';

COMMENT ON TABLE notificaciones IS
    'Notificaciones internas, push, correo o SMS.';

COMMENT ON TABLE notificacion_dispositivos IS
    'Estado de envío de una notificación en cada dispositivo.';