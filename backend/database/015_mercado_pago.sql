CREATE TABLE IF NOT EXISTS mercado_pago_preferencias
(
    id_preferencia BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pedido BIGINT
        NOT NULL,

    id_pago BIGINT
        NOT NULL,

    preference_id VARCHAR(255)
        NOT NULL,

    init_point TEXT,

    sandbox_init_point TEXT,

    external_reference VARCHAR(255),

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'CREADA',

    payload_solicitud JSONB,

    payload_respuesta JSONB,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_mp_preferencias_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_mp_preferencias_pago
        FOREIGN KEY (id_pago)
        REFERENCES pagos(id_pago)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_mp_preferencias_preference_id
        UNIQUE (preference_id),

    CONSTRAINT ck_mp_preferencias_estado
        CHECK
        (
            estado IN
            (
                'CREADA',
                'UTILIZADA',
                'VENCIDA',
                'CANCELADA'
            )
        )
);


CREATE TABLE IF NOT EXISTS mercado_pago_webhooks
(
    id_webhook BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    tipo VARCHAR(100),

    accion VARCHAR(100),

    data_id VARCHAR(255),

    request_id VARCHAR(255),

    firma VARCHAR(1000),

    payload JSONB
        NOT NULL,

    procesado BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    intentos INTEGER
        NOT NULL
        DEFAULT 0,

    mensaje_error TEXT,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_procesado TIMESTAMPTZ,

    CONSTRAINT ck_mp_webhooks_intentos
        CHECK (intentos >= 0)
);


CREATE INDEX IF NOT EXISTS
    ix_mp_preferencias_id_pedido
ON mercado_pago_preferencias(id_pedido);


CREATE INDEX IF NOT EXISTS
    ix_mp_preferencias_id_pago
ON mercado_pago_preferencias(id_pago);


CREATE INDEX IF NOT EXISTS
    ix_mp_preferencias_estado
ON mercado_pago_preferencias(estado);


CREATE INDEX IF NOT EXISTS
    ix_mp_webhooks_data_id
ON mercado_pago_webhooks(data_id);


CREATE INDEX IF NOT EXISTS
    ix_mp_webhooks_procesado
ON mercado_pago_webhooks(procesado, fecha_creacion);


CREATE INDEX IF NOT EXISTS
    ix_mp_webhooks_pendientes
ON mercado_pago_webhooks(fecha_creacion)
WHERE procesado = FALSE;


COMMENT ON TABLE mercado_pago_preferencias IS
    'Preferencias de pago generadas en Mercado Pago.';

COMMENT ON TABLE mercado_pago_webhooks IS
    'Notificaciones recibidas desde Mercado Pago.';