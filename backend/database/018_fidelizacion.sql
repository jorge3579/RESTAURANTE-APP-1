CREATE TABLE IF NOT EXISTS configuracion_fidelizacion
(
    id_configuracion_fidelizacion INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(100)
        NOT NULL,

    valor NUMERIC(14, 2)
        NOT NULL,

    descripcion VARCHAR(500),

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_configuracion_fidelizacion_nombre
        UNIQUE (nombre)
);


CREATE TABLE IF NOT EXISTS niveles_vip
(
    id_nivel_vip INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(100)
        NOT NULL,

    orden_nivel INTEGER
        NOT NULL,

    compras_minimas INTEGER
        NOT NULL
        DEFAULT 0,

    monto_minimo NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    descuento_porcentaje NUMERIC(5, 2)
        NOT NULL
        DEFAULT 0,

    descripcion VARCHAR(500),

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_niveles_vip_nombre
        UNIQUE (nombre),

    CONSTRAINT uq_niveles_vip_orden
        UNIQUE (orden_nivel),

    CONSTRAINT ck_niveles_vip_orden
        CHECK (orden_nivel >= 0),

    CONSTRAINT ck_niveles_vip_compras
        CHECK (compras_minimas >= 0),

    CONSTRAINT ck_niveles_vip_monto
        CHECK (monto_minimo >= 0),

    CONSTRAINT ck_niveles_vip_descuento
        CHECK
        (
            descuento_porcentaje
            BETWEEN 0 AND 100
        )
);


CREATE TABLE IF NOT EXISTS puntos_usuario
(
    id_puntos_usuario BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_nivel_vip INTEGER,

    puntos_disponibles INTEGER
        NOT NULL
        DEFAULT 0,

    puntos_acumulados INTEGER
        NOT NULL
        DEFAULT 0,

    compras_acumuladas INTEGER
        NOT NULL
        DEFAULT 0,

    monto_acumulado NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    fecha_ultima_compra TIMESTAMPTZ,

    fecha_evaluacion_nivel TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_puntos_usuario_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_puntos_usuario_nivel
        FOREIGN KEY (id_nivel_vip)
        REFERENCES niveles_vip(id_nivel_vip)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT uq_puntos_usuario_usuario
        UNIQUE (id_usuario),

    CONSTRAINT ck_puntos_usuario_puntos_disponibles
        CHECK (puntos_disponibles >= 0),

    CONSTRAINT ck_puntos_usuario_puntos_acumulados
        CHECK (puntos_acumulados >= 0),

    CONSTRAINT ck_puntos_usuario_compras
        CHECK (compras_acumuladas >= 0),

    CONSTRAINT ck_puntos_usuario_monto
        CHECK (monto_acumulado >= 0)
);


CREATE TABLE IF NOT EXISTS historial_puntos
(
    id_historial_puntos BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_pedido BIGINT,

    tipo_movimiento VARCHAR(30)
        NOT NULL,

    puntos INTEGER
        NOT NULL,

    saldo_anterior INTEGER
        NOT NULL,

    saldo_posterior INTEGER
        NOT NULL,

    descripcion VARCHAR(500),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_historial_puntos_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_historial_puntos_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_historial_puntos_tipo
        CHECK
        (
            tipo_movimiento IN
            (
                'ACUMULACION',
                'CANJE',
                'AJUSTE_POSITIVO',
                'AJUSTE_NEGATIVO',
                'VENCIMIENTO',
                'ANULACION'
            )
        ),

    CONSTRAINT ck_historial_puntos_puntos
        CHECK (puntos > 0),

    CONSTRAINT ck_historial_puntos_saldos
        CHECK
        (
            saldo_anterior >= 0
            AND saldo_posterior >= 0
        )
);


CREATE TABLE IF NOT EXISTS premios_generados
(
    id_premio BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    codigo UUID
        NOT NULL
        DEFAULT gen_random_uuid(),

    tipo_premio VARCHAR(40)
        NOT NULL,

    descripcion VARCHAR(500)
        NOT NULL,

    valor NUMERIC(14, 2),

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'DISPONIBLE',

    fecha_generacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_vencimiento TIMESTAMPTZ,

    fecha_canje TIMESTAMPTZ,

    id_pedido_canje BIGINT,

    CONSTRAINT fk_premios_generados_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_premios_generados_pedido
        FOREIGN KEY (id_pedido_canje)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT uq_premios_generados_codigo
        UNIQUE (codigo),

    CONSTRAINT ck_premios_generados_tipo
        CHECK
        (
            tipo_premio IN
            (
                'COMIDA_GRATIS',
                'BEBIDA_GRATIS',
                'COMIDA_Y_BEBIDA',
                'DESCUENTO',
                'PRODUCTO'
            )
        ),

    CONSTRAINT ck_premios_generados_estado
        CHECK
        (
            estado IN
            (
                'DISPONIBLE',
                'CANJEADO',
                'VENCIDO',
                'CANCELADO'
            )
        ),

    CONSTRAINT ck_premios_generados_valor
        CHECK
        (
            valor IS NULL
            OR valor >= 0
        )
);


CREATE TABLE IF NOT EXISTS historial_vip
(
    id_historial_vip BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_nivel_anterior INTEGER,

    id_nivel_nuevo INTEGER,

    motivo VARCHAR(500),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_historial_vip_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_historial_vip_nivel_anterior
        FOREIGN KEY (id_nivel_anterior)
        REFERENCES niveles_vip(id_nivel_vip)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_historial_vip_nivel_nuevo
        FOREIGN KEY (id_nivel_nuevo)
        REFERENCES niveles_vip(id_nivel_vip)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


CREATE INDEX IF NOT EXISTS
    ix_puntos_usuario_id_usuario
ON puntos_usuario(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_puntos_usuario_id_nivel
ON puntos_usuario(id_nivel_vip);


CREATE INDEX IF NOT EXISTS
    ix_historial_puntos_usuario
ON historial_puntos(id_usuario, fecha_creacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_historial_puntos_pedido
ON historial_puntos(id_pedido);


CREATE INDEX IF NOT EXISTS
    ix_premios_generados_usuario
ON premios_generados(id_usuario, fecha_generacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_premios_generados_disponibles
ON premios_generados(id_usuario, fecha_vencimiento)
WHERE estado = 'DISPONIBLE';


CREATE INDEX IF NOT EXISTS
    ix_historial_vip_usuario
ON historial_vip(id_usuario, fecha_creacion DESC);


COMMENT ON TABLE puntos_usuario IS
    'Resumen actual de puntos, compras y nivel VIP de cada usuario.';

COMMENT ON TABLE historial_puntos IS
    'Movimientos de acumulación y canje de puntos.';

COMMENT ON TABLE premios_generados IS
    'Premios obtenidos por fidelización.';

COMMENT ON TABLE historial_vip IS
    'Cambios de nivel VIP de cada cliente.';