CREATE TABLE IF NOT EXISTS configuracion_sistema
(
    id_configuracion INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    clave VARCHAR(150)
        NOT NULL,

    valor TEXT,

    tipo_dato VARCHAR(30)
        NOT NULL
        DEFAULT 'TEXTO',

    descripcion VARCHAR(500),

    categoria VARCHAR(100),

    editable BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_configuracion_sistema_clave
        UNIQUE (clave),

    CONSTRAINT ck_configuracion_sistema_tipo_dato
        CHECK
        (
            tipo_dato IN
            (
                'TEXTO',
                'ENTERO',
                'DECIMAL',
                'BOOLEANO',
                'FECHA',
                'HORA',
                'JSON'
            )
        )
);


CREATE TABLE IF NOT EXISTS politicas_sistema
(
    id_politica INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    codigo VARCHAR(100)
        NOT NULL,

    nombre VARCHAR(200)
        NOT NULL,

    contenido TEXT
        NOT NULL,

    version VARCHAR(30)
        NOT NULL,

    obligatoria BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_vigencia TIMESTAMPTZ
        NOT NULL,

    activa BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_politicas_sistema_codigo_version
        UNIQUE
        (
            codigo,
            version
        )
);


CREATE TABLE IF NOT EXISTS aceptaciones_politicas
(
    id_aceptacion_politica BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_politica INTEGER
        NOT NULL,

    aceptada BOOLEAN
        NOT NULL,

    ip VARCHAR(50),

    dispositivo VARCHAR(255),

    user_agent TEXT,

    fecha_aceptacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_aceptaciones_politicas_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_aceptaciones_politicas_politica
        FOREIGN KEY (id_politica)
        REFERENCES politicas_sistema(id_politica)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_aceptaciones_politicas
        UNIQUE
        (
            id_usuario,
            id_politica
        )
);


CREATE INDEX IF NOT EXISTS
    ix_configuracion_sistema_categoria
ON configuracion_sistema(categoria);


CREATE INDEX IF NOT EXISTS
    ix_configuracion_sistema_activo
ON configuracion_sistema(activo);


CREATE INDEX IF NOT EXISTS
    ix_politicas_sistema_activas
ON politicas_sistema
(
    codigo,
    fecha_vigencia DESC
)
WHERE activa = TRUE;


CREATE INDEX IF NOT EXISTS
    ix_aceptaciones_politicas_usuario
ON aceptaciones_politicas
(
    id_usuario,
    fecha_aceptacion DESC
);


COMMENT ON TABLE configuracion_sistema IS
    'Parámetros generales configurables del sistema.';

COMMENT ON TABLE politicas_sistema IS
    'Versiones de términos, condiciones y políticas.';

COMMENT ON TABLE aceptaciones_politicas IS
    'Registro de aceptación de políticas por usuario.';