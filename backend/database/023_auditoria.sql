CREATE TABLE IF NOT EXISTS auditoria
(
    id_auditoria BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER,

    modulo VARCHAR(100)
        NOT NULL,

    accion VARCHAR(100)
        NOT NULL,

    descripcion TEXT,

    entidad VARCHAR(100),

    id_entidad BIGINT,

    datos_anteriores JSONB,

    datos_nuevos JSONB,

    ip VARCHAR(50),

    user_agent TEXT,

    request_id UUID,

    metodo_http VARCHAR(10),

    ruta TEXT,

    codigo_respuesta INTEGER,

    duracion_milisegundos NUMERIC(14, 3),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_auditoria_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_auditoria_codigo_respuesta
        CHECK
        (
            codigo_respuesta IS NULL
            OR codigo_respuesta
                BETWEEN 100 AND 599
        ),

    CONSTRAINT ck_auditoria_duracion
        CHECK
        (
            duracion_milisegundos IS NULL
            OR duracion_milisegundos >= 0
        )
);


CREATE INDEX IF NOT EXISTS
    ix_auditoria_id_usuario
ON auditoria(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_auditoria_fecha
ON auditoria(fecha_creacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_auditoria_modulo_accion
ON auditoria
(
    modulo,
    accion,
    fecha_creacion DESC
);


CREATE INDEX IF NOT EXISTS
    ix_auditoria_entidad
ON auditoria
(
    entidad,
    id_entidad
);


CREATE INDEX IF NOT EXISTS
    ix_auditoria_request_id
ON auditoria(request_id);


CREATE INDEX IF NOT EXISTS
    ix_auditoria_datos_anteriores
ON auditoria
USING GIN(datos_anteriores);


CREATE INDEX IF NOT EXISTS
    ix_auditoria_datos_nuevos
ON auditoria
USING GIN(datos_nuevos);


COMMENT ON TABLE auditoria IS
    'Registro histórico de acciones y cambios realizados en el sistema.';