CREATE TABLE IF NOT EXISTS categorias
(
    id_categoria INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(100)
        NOT NULL,

    descripcion VARCHAR(500),

    imagen_url TEXT,

    orden_visual INTEGER
        NOT NULL
        DEFAULT 0,

    activa BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT uq_categorias_nombre
        UNIQUE (nombre),

    CONSTRAINT ck_categorias_nombre
        CHECK (LENGTH(TRIM(nombre)) >= 2),

    CONSTRAINT ck_categorias_orden
        CHECK (orden_visual >= 0)
);


CREATE TABLE IF NOT EXISTS productos
(
    id_producto INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_categoria INTEGER
        NOT NULL,

    codigo VARCHAR(50),

    nombre VARCHAR(150)
        NOT NULL,

    descripcion VARCHAR(1000),

    precio NUMERIC(12, 2)
        NOT NULL,

    costo NUMERIC(12, 2),

    imagen_url TEXT,

    tiempo_preparacion_minutos INTEGER,

    disponible BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    permite_take_away BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    permite_consumo_local BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    controla_stock BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    destacado BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_productos_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categorias(id_categoria)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_productos_codigo
        UNIQUE (codigo),

    CONSTRAINT ck_productos_nombre
        CHECK (LENGTH(TRIM(nombre)) >= 2),

    CONSTRAINT ck_productos_precio
        CHECK (precio >= 0),

    CONSTRAINT ck_productos_costo
        CHECK
        (
            costo IS NULL
            OR costo >= 0
        ),

    CONSTRAINT ck_productos_tiempo_preparacion
        CHECK
        (
            tiempo_preparacion_minutos IS NULL
            OR tiempo_preparacion_minutos >= 0
        ),

    CONSTRAINT ck_productos_tipo_consumo
        CHECK
        (
            permite_take_away = TRUE
            OR permite_consumo_local = TRUE
        )
);


CREATE TABLE IF NOT EXISTS productos_sucursal
(
    id_producto_sucursal BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_producto INTEGER
        NOT NULL,

    id_sucursal INTEGER
        NOT NULL,

    precio NUMERIC(12, 2),

    disponible BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_productos_sucursal_producto
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_productos_sucursal_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_productos_sucursal
        UNIQUE (id_producto, id_sucursal),

    CONSTRAINT ck_productos_sucursal_precio
        CHECK
        (
            precio IS NULL
            OR precio >= 0
        )
);


CREATE INDEX IF NOT EXISTS
    ix_productos_id_categoria
ON productos(id_categoria);


CREATE INDEX IF NOT EXISTS
    ix_productos_activo_disponible
ON productos(activo, disponible);


CREATE INDEX IF NOT EXISTS
    ix_productos_nombre
ON productos(nombre);


CREATE INDEX IF NOT EXISTS
    ix_productos_sucursal_id_sucursal
ON productos_sucursal(id_sucursal);


CREATE INDEX IF NOT EXISTS
    ix_productos_sucursal_disponibles
ON productos_sucursal(id_sucursal, id_producto)
WHERE disponible = TRUE;


COMMENT ON TABLE categorias IS
    'Categorías utilizadas para ordenar el menú.';

COMMENT ON TABLE productos IS
    'Platos, bebidas y productos ofrecidos por el restaurante.';

COMMENT ON TABLE productos_sucursal IS
    'Disponibilidad y precio específico de un producto por sucursal.';