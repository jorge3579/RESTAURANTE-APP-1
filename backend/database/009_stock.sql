CREATE TABLE IF NOT EXISTS ingredientes
(
    id_ingrediente INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_sucursal INTEGER
        NOT NULL,

    codigo VARCHAR(50),

    nombre VARCHAR(150)
        NOT NULL,

    descripcion VARCHAR(500),

    unidad_medida VARCHAR(30)
        NOT NULL,

    stock_actual NUMERIC(14, 3)
        NOT NULL
        DEFAULT 0,

    stock_minimo NUMERIC(14, 3)
        NOT NULL
        DEFAULT 0,

    costo_unitario NUMERIC(12, 2),

    controla_stock BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_ingredientes_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_ingredientes_codigo_sucursal
        UNIQUE (id_sucursal, codigo),

    CONSTRAINT uq_ingredientes_nombre_sucursal
        UNIQUE (id_sucursal, nombre),

    CONSTRAINT ck_ingredientes_stock_actual
        CHECK (stock_actual >= 0),

    CONSTRAINT ck_ingredientes_stock_minimo
        CHECK (stock_minimo >= 0),

    CONSTRAINT ck_ingredientes_costo
        CHECK
        (
            costo_unitario IS NULL
            OR costo_unitario >= 0
        ),

    CONSTRAINT ck_ingredientes_unidad
        CHECK
        (
            unidad_medida IN
            (
                'UNIDAD',
                'GRAMO',
                'KILOGRAMO',
                'MILILITRO',
                'LITRO',
                'PORCION'
            )
        )
);


CREATE TABLE IF NOT EXISTS producto_ingredientes
(
    id_producto_ingrediente BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_producto INTEGER
        NOT NULL,

    id_ingrediente INTEGER
        NOT NULL,

    cantidad NUMERIC(14, 3)
        NOT NULL,

    opcional BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_producto_ingredientes_producto
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_producto_ingredientes_ingrediente
        FOREIGN KEY (id_ingrediente)
        REFERENCES ingredientes(id_ingrediente)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_producto_ingredientes
        UNIQUE (id_producto, id_ingrediente),

    CONSTRAINT ck_producto_ingredientes_cantidad
        CHECK (cantidad > 0)
);


CREATE TABLE IF NOT EXISTS movimientos_stock
(
    id_movimiento_stock BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_ingrediente INTEGER
        NOT NULL,

    id_usuario INTEGER,

    tipo_movimiento VARCHAR(30)
        NOT NULL,

    cantidad NUMERIC(14, 3)
        NOT NULL,

    stock_anterior NUMERIC(14, 3)
        NOT NULL,

    stock_posterior NUMERIC(14, 3)
        NOT NULL,

    motivo VARCHAR(255),

    referencia_tipo VARCHAR(50),

    referencia_id BIGINT,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_movimientos_stock_ingrediente
        FOREIGN KEY (id_ingrediente)
        REFERENCES ingredientes(id_ingrediente)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimientos_stock_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_movimientos_stock_tipo
        CHECK
        (
            tipo_movimiento IN
            (
                'ENTRADA',
                'SALIDA',
                'AJUSTE_POSITIVO',
                'AJUSTE_NEGATIVO',
                'CONSUMO_PEDIDO',
                'DEVOLUCION',
                'MERMA'
            )
        ),

    CONSTRAINT ck_movimientos_stock_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_movimientos_stock_stock_anterior
        CHECK (stock_anterior >= 0),

    CONSTRAINT ck_movimientos_stock_stock_posterior
        CHECK (stock_posterior >= 0)
);


CREATE INDEX IF NOT EXISTS
    ix_ingredientes_id_sucursal
ON ingredientes(id_sucursal);


CREATE INDEX IF NOT EXISTS
    ix_ingredientes_stock_bajo
ON ingredientes(id_sucursal, stock_actual, stock_minimo)
WHERE activo = TRUE
  AND controla_stock = TRUE;


CREATE INDEX IF NOT EXISTS
    ix_producto_ingredientes_producto
ON producto_ingredientes(id_producto);


CREATE INDEX IF NOT EXISTS
    ix_producto_ingredientes_ingrediente
ON producto_ingredientes(id_ingrediente);


CREATE INDEX IF NOT EXISTS
    ix_movimientos_stock_ingrediente
ON movimientos_stock(id_ingrediente, fecha_creacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_movimientos_stock_usuario
ON movimientos_stock(id_usuario);


COMMENT ON TABLE ingredientes IS
    'Ingredientes y existencias disponibles por sucursal.';

COMMENT ON TABLE producto_ingredientes IS
    'Receta o composición de cada producto.';

COMMENT ON TABLE movimientos_stock IS
    'Historial de entradas, salidas, consumos y ajustes de stock.';