CREATE TABLE IF NOT EXISTS reservas
(
    id_reserva BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_sucursal INTEGER
        NOT NULL,

    codigo_reserva UUID
        NOT NULL
        DEFAULT gen_random_uuid(),

    fecha_reserva DATE
        NOT NULL,

    hora_reserva TIME
        NOT NULL,

    cantidad_personas INTEGER
        NOT NULL,

    tipo_consumo VARCHAR(30)
        NOT NULL
        DEFAULT 'LOCAL',

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    observaciones VARCHAR(1000),

    acepta_politica_cancelacion BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    acepta_politica_no_show BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    fecha_confirmacion TIMESTAMPTZ,

    fecha_cancelacion TIMESTAMPTZ,

    motivo_cancelacion VARCHAR(500),

    fecha_llegada TIMESTAMPTZ,

    fecha_finalizacion TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_reservas_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_reservas_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_reservas_codigo
        UNIQUE (codigo_reserva),

    CONSTRAINT ck_reservas_cantidad_personas
        CHECK (cantidad_personas > 0),

    CONSTRAINT ck_reservas_tipo_consumo
        CHECK
        (
            tipo_consumo IN
            (
                'LOCAL',
                'TAKE_AWAY'
            )
        ),

    CONSTRAINT ck_reservas_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'PENDIENTE_PAGO',
                'CONFIRMADA',
                'EN_CURSO',
                'FINALIZADA',
                'CANCELADA',
                'NO_ASISTIO',
                'VENCIDA'
            )
        ),

    CONSTRAINT ck_reservas_fecha
        CHECK
        (
            fecha_reserva >= DATE '2020-01-01'
        )
);


/*
Una reserva puede utilizar una o varias mesas.

Esto permite unir mesas para grupos grandes.
*/

CREATE TABLE IF NOT EXISTS reserva_mesas
(
    id_reserva_mesa BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_reserva BIGINT
        NOT NULL,

    id_mesa INTEGER
        NOT NULL,

    fecha_asignacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    liberada BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    fecha_liberacion TIMESTAMPTZ,

    CONSTRAINT fk_reserva_mesas_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES reservas(id_reserva)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_reserva_mesas_mesa
        FOREIGN KEY (id_mesa)
        REFERENCES mesas(id_mesa)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_reserva_mesas
        UNIQUE (id_reserva, id_mesa)
);


/*
Historial de cambios de estado de las reservas.
*/

CREATE TABLE IF NOT EXISTS historial_reservas
(
    id_historial_reserva BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_reserva BIGINT
        NOT NULL,

    id_usuario INTEGER,

    estado_anterior VARCHAR(30),

    estado_nuevo VARCHAR(30)
        NOT NULL,

    observaciones VARCHAR(500),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_historial_reservas_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES reservas(id_reserva)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_historial_reservas_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


CREATE INDEX IF NOT EXISTS
    ix_reservas_id_usuario
ON reservas(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_reservas_id_sucursal
ON reservas(id_sucursal);


CREATE INDEX IF NOT EXISTS
    ix_reservas_fecha_hora
ON reservas(id_sucursal, fecha_reserva, hora_reserva);


CREATE INDEX IF NOT EXISTS
    ix_reservas_estado
ON reservas(estado);


CREATE INDEX IF NOT EXISTS
    ix_reservas_pendientes
ON reservas(fecha_reserva, hora_reserva)
WHERE estado IN
(
    'PENDIENTE',
    'PENDIENTE_PAGO',
    'CONFIRMADA'
);


CREATE INDEX IF NOT EXISTS
    ix_reserva_mesas_id_reserva
ON reserva_mesas(id_reserva);


CREATE INDEX IF NOT EXISTS
    ix_reserva_mesas_id_mesa
ON reserva_mesas(id_mesa);


CREATE INDEX IF NOT EXISTS
    ix_historial_reservas_id_reserva
ON historial_reservas(id_reserva, fecha_creacion DESC);


COMMENT ON TABLE reservas IS
    'Reservas realizadas por los clientes.';

COMMENT ON TABLE reserva_mesas IS
    'Mesas asignadas a cada reserva, incluyendo unión de mesas.';

COMMENT ON TABLE historial_reservas IS
    'Historial de cambios de estado de las reservas.';