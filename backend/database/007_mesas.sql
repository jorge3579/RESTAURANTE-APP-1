CREATE TABLE IF NOT EXISTS mesas
(
    id_mesa INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_sucursal INTEGER
        NOT NULL,

    numero VARCHAR(20)
        NOT NULL,

    nombre VARCHAR(100),

    capacidad INTEGER
        NOT NULL,

    capacidad_maxima INTEGER,

    ubicacion VARCHAR(100),

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'LIBRE',

    permite_union BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    activa BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_mesas_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_mesas_sucursal_numero
        UNIQUE (id_sucursal, numero),

    CONSTRAINT ck_mesas_capacidad
        CHECK (capacidad > 0),

    CONSTRAINT ck_mesas_capacidad_maxima
        CHECK
        (
            capacidad_maxima IS NULL
            OR capacidad_maxima >= capacidad
        ),

    CONSTRAINT ck_mesas_estado
        CHECK
        (
            estado IN
            (
                'LIBRE',
                'RESERVADA',
                'OCUPADA',
                'LIMPIEZA',
                'FUERA_SERVICIO'
            )
        )
);


CREATE TABLE IF NOT EXISTS grupos_mesas
(
    id_grupo_mesas INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_sucursal INTEGER
        NOT NULL,

    nombre VARCHAR(100)
        NOT NULL,

    capacidad_total INTEGER
        NOT NULL,

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_grupos_mesas_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_grupos_mesas_nombre
        UNIQUE (id_sucursal, nombre),

    CONSTRAINT ck_grupos_mesas_capacidad
        CHECK (capacidad_total > 0)
);


CREATE TABLE IF NOT EXISTS grupo_mesas_detalle
(
    id_grupo_mesa_detalle BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_grupo_mesas INTEGER
        NOT NULL,

    id_mesa INTEGER
        NOT NULL,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_grupo_mesas_detalle_grupo
        FOREIGN KEY (id_grupo_mesas)
        REFERENCES grupos_mesas(id_grupo_mesas)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_grupo_mesas_detalle_mesa
        FOREIGN KEY (id_mesa)
        REFERENCES mesas(id_mesa)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_grupo_mesas_detalle
        UNIQUE (id_grupo_mesas, id_mesa)
);


CREATE INDEX IF NOT EXISTS
    ix_mesas_id_sucursal
ON mesas(id_sucursal);


CREATE INDEX IF NOT EXISTS
    ix_mesas_estado
ON mesas(id_sucursal, estado);


CREATE INDEX IF NOT EXISTS
    ix_mesas_disponibles
ON mesas(id_sucursal, capacidad)
WHERE activa = TRUE
  AND estado = 'LIBRE';


CREATE INDEX IF NOT EXISTS
    ix_grupos_mesas_id_sucursal
ON grupos_mesas(id_sucursal);


COMMENT ON TABLE mesas IS
    'Mesas individuales disponibles en cada sucursal.';

COMMENT ON TABLE grupos_mesas IS
    'Agrupaciones configurables de mesas para grupos grandes.';

COMMENT ON TABLE grupo_mesas_detalle IS
    'Mesas que forman parte de una agrupación.';