CREATE TABLE IF NOT EXISTS pedidos
(
    id_pedido BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_sucursal INTEGER
        NOT NULL,

    id_reserva BIGINT,

    numero_pedido VARCHAR(50),

    tipo_consumo VARCHAR(30)
        NOT NULL
        DEFAULT 'LOCAL',

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'CREADO',

    subtotal NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    descuento NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    recargo NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    total NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    observaciones VARCHAR(1000),

    fecha_confirmacion TIMESTAMPTZ,

    fecha_inicio_preparacion TIMESTAMPTZ,

    fecha_listo TIMESTAMPTZ,

    fecha_entrega TIMESTAMPTZ,

    fecha_cancelacion TIMESTAMPTZ,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_pedidos_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pedidos_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pedidos_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES reservas(id_reserva)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT uq_pedidos_numero
        UNIQUE (numero_pedido),

    CONSTRAINT ck_pedidos_tipo_consumo
        CHECK
        (
            tipo_consumo IN
            (
                'LOCAL',
                'TAKE_AWAY'
            )
        ),

    CONSTRAINT ck_pedidos_estado
        CHECK
        (
            estado IN
            (
                'CREADO',
                'PENDIENTE_PAGO',
                'PAGADO',
                'CONFIRMADO',
                'EN_COCINA',
                'EN_PREPARACION',
                'LISTO',
                'ENTREGADO',
                'FINALIZADO',
                'CANCELADO'
            )
        ),

    CONSTRAINT ck_pedidos_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT ck_pedidos_descuento
        CHECK (descuento >= 0),

    CONSTRAINT ck_pedidos_recargo
        CHECK (recargo >= 0),

    CONSTRAINT ck_pedidos_total
        CHECK (total >= 0),

    CONSTRAINT ck_pedidos_calculo_total
        CHECK
        (
            total =
            subtotal
            - descuento
            + recargo
        )
);


CREATE TABLE IF NOT EXISTS pedido_detalles
(
    id_pedido_detalle BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pedido BIGINT
        NOT NULL,

    id_producto INTEGER
        NOT NULL,

    nombre_producto VARCHAR(150)
        NOT NULL,

    cantidad INTEGER
        NOT NULL,

    precio_unitario NUMERIC(14, 2)
        NOT NULL,

    descuento NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    subtotal NUMERIC(14, 2)
        NOT NULL,

    observaciones VARCHAR(500),

    estado_cocina VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDIENTE',

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_pedido_detalles_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_pedido_detalles_producto
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_pedido_detalles_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_pedido_detalles_precio
        CHECK (precio_unitario >= 0),

    CONSTRAINT ck_pedido_detalles_descuento
        CHECK (descuento >= 0),

    CONSTRAINT ck_pedido_detalles_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT ck_pedido_detalles_estado_cocina
        CHECK
        (
            estado_cocina IN
            (
                'PENDIENTE',
                'EN_PREPARACION',
                'LISTO',
                'ENTREGADO',
                'CANCELADO'
            )
        )
);


/*
Historial de cambios de estado del pedido.
*/

CREATE TABLE IF NOT EXISTS historial_pedidos
(
    id_historial_pedido BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pedido BIGINT
        NOT NULL,

    id_usuario INTEGER,

    estado_anterior VARCHAR(30),

    estado_nuevo VARCHAR(30)
        NOT NULL,

    observaciones VARCHAR(500),

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_historial_pedidos_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id_pedido)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_historial_pedidos_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


CREATE INDEX IF NOT EXISTS
    ix_pedidos_id_usuario
ON pedidos(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_pedidos_id_sucursal
ON pedidos(id_sucursal);


CREATE INDEX IF NOT EXISTS
    ix_pedidos_id_reserva
ON pedidos(id_reserva);


CREATE INDEX IF NOT EXISTS
    ix_pedidos_estado
ON pedidos(estado);


CREATE INDEX IF NOT EXISTS
    ix_pedidos_fecha_creacion
ON pedidos(fecha_creacion DESC);


CREATE INDEX IF NOT EXISTS
    ix_pedidos_activos
ON pedidos(id_sucursal, fecha_creacion DESC)
WHERE estado NOT IN
(
    'FINALIZADO',
    'CANCELADO'
);


CREATE INDEX IF NOT EXISTS
    ix_pedido_detalles_id_pedido
ON pedido_detalles(id_pedido);


CREATE INDEX IF NOT EXISTS
    ix_pedido_detalles_id_producto
ON pedido_detalles(id_producto);


CREATE INDEX IF NOT EXISTS
    ix_pedido_detalles_estado_cocina
ON pedido_detalles(estado_cocina);


CREATE INDEX IF NOT EXISTS
    ix_historial_pedidos_id_pedido
ON historial_pedidos(id_pedido, fecha_creacion DESC);


COMMENT ON TABLE pedidos IS
    'Pedidos realizados por clientes o personal del restaurante.';

COMMENT ON TABLE pedido_detalles IS
    'Productos y cantidades que forman parte de cada pedido.';

COMMENT ON TABLE historial_pedidos IS
    'Historial de estados de los pedidos.';