CREATE TABLE IF NOT EXISTS usuarios
(
    id_usuario INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_rol_principal INTEGER
        NOT NULL,

    nombre VARCHAR(100)
        NOT NULL,

    apellido VARCHAR(100)
        NOT NULL,

    dni VARCHAR(20),

    email CITEXT
        NOT NULL,

    telefono VARCHAR(50),

    password_hash VARCHAR(255)
        NOT NULL,

    email_verificado BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    ultimo_login TIMESTAMPTZ,

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_registro TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_usuarios_rol_principal
        FOREIGN KEY (id_rol_principal)
        REFERENCES roles(id_rol)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_usuarios_email
        UNIQUE (email),

    CONSTRAINT uq_usuarios_dni
        UNIQUE (dni),

    CONSTRAINT ck_usuarios_nombre
        CHECK (LENGTH(TRIM(nombre)) >= 2),

    CONSTRAINT ck_usuarios_apellido
        CHECK (LENGTH(TRIM(apellido)) >= 2),

    CONSTRAINT ck_usuarios_email
        CHECK (POSITION('@' IN email::TEXT) > 1)
);


/*
Un usuario puede tener más de un rol.

El campo id_rol_principal de usuarios se mantiene para que
el backend actual pueda continuar trabajando sin grandes cambios.
*/

CREATE TABLE IF NOT EXISTS usuario_roles
(
    id_usuario_rol BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    id_rol INTEGER
        NOT NULL,

    es_principal BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    activo BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    fecha_asignacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_usuario_roles_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_usuario_roles_rol
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_usuario_roles
        UNIQUE (id_usuario, id_rol)
);


/*
Refresh tokens utilizados para mantener la sesión iniciada.
*/

CREATE TABLE IF NOT EXISTS refresh_tokens
(
    id_refresh_token BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario INTEGER
        NOT NULL,

    token UUID
        NOT NULL
        DEFAULT gen_random_uuid(),

    token_hash VARCHAR(255),

    fecha_expiracion TIMESTAMPTZ
        NOT NULL,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_revocacion TIMESTAMPTZ,

    revocado BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    dispositivo VARCHAR(255),

    ip VARCHAR(50),

    CONSTRAINT fk_refresh_tokens_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_refresh_tokens_token
        UNIQUE (token)
);


CREATE INDEX IF NOT EXISTS
    ix_usuarios_id_rol_principal
ON usuarios(id_rol_principal);


CREATE INDEX IF NOT EXISTS
    ix_usuarios_activo
ON usuarios(activo);


CREATE INDEX IF NOT EXISTS
    ix_usuario_roles_id_usuario
ON usuario_roles(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_usuario_roles_id_rol
ON usuario_roles(id_rol);


CREATE INDEX IF NOT EXISTS
    ix_refresh_tokens_id_usuario
ON refresh_tokens(id_usuario);


CREATE INDEX IF NOT EXISTS
    ix_refresh_tokens_fecha_expiracion
ON refresh_tokens(fecha_expiracion);


CREATE INDEX IF NOT EXISTS
    ix_refresh_tokens_activos
ON refresh_tokens(id_usuario, fecha_expiracion)
WHERE revocado = FALSE;


COMMENT ON TABLE usuarios IS
    'Clientes, administradores y empleados de SmartRestaurantQR.';

COMMENT ON COLUMN usuarios.id_rol_principal IS
    'Rol principal utilizado por el backend y las aplicaciones.';

COMMENT ON TABLE usuario_roles IS
    'Roles adicionales que puede tener un mismo usuario.';

COMMENT ON TABLE refresh_tokens IS
    'Tokens utilizados para renovar sesiones JWT.';