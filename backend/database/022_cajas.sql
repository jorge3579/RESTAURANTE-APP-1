CREATE TABLE IF NOT EXISTS cajas
(
    id_caja BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_sucursal INTEGER
        NOT NULL,

    id_usuario_apertura INTEGER
        NOT NULL,

    id_usuario_cierre INTEGER,

    fecha_apertura TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_cierre TIMESTAMPTZ,

    monto_inicial NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    monto_final_declarado NUMERIC(14, 2),

    monto_final_calculado NUMERIC(14, 2),

    diferencia NUMERIC(14, 2),

    total_ventas NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    total_efectivo NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    total_mercado_pago NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    total_payway NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    total_transferencias NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    total_creditos NUMERIC(14, 2)
        NOT NULL
        DEFAULT 0,

    estado VARCHAR(30)
        NOT NULL
        DEFAULT 'ABIERTA',

    observaciones TEXT,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_modificacion TIMESTAMPTZ,

    CONSTRAINT fk_cajas_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_cajas_usuario_apertura
        FOREIGN KEY (id_usuario_apertura)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_cajas_usuario_cierre
        FOREIGN KEY (id_usuario_cierre)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_cajas_monto_inicial
        CHECK (monto_inicial >= 0),

    CONSTRAINT ck_cajas_monto_final_declarado
        CHECK
        (
            monto_final_declarado IS NULL
            OR monto_final_declarado >= 0
        ),

    CONSTRAINT ck_cajas_monto_final_calculado
        CHECK
        (
            monto_final_calculado IS NULL
            OR monto_final_calculado >= 0
        ),

    CONSTRAINT ck_cajas_estado
        CHECK
        (
            estado IN
            (
                'ABIERTA',
                'CERRADA',
                'ANULADA'
            )
        )
);


CREATE UNIQUE INDEX IF NOT EXISTS
    uq_caja_abierta_sucursal
ON cajas(id_sucursal)
WHERE estado = 'ABIERTA';


CREATE TABLE IF NOT EXISTS movimientos_caja
(
    id_movimiento_caja BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_caja BIGINT
        NOT NULL,

    id_usuario INTEGER
        NOT NULL,

    id_pago BIGINT,

    tipo_movimiento VARCHAR(30)
        NOT NULL,

    medio_pago VARCHAR(50),

    concepto VARCHAR(500)
        NOT NULL,

    monto NUMERIC(14, 2)
        NOT NULL,

    saldo_anterior NUMERIC(14, 2),

    saldo_posterior NUMERIC(14, 2),

    referencia_tipo VARCHAR(50),

    referencia_id BIGINT,

    fecha_creacion TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_movimientos_caja_caja
        FOREIGN KEY (id_caja)
        REFERENCES cajas(id_caja)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_movimientos_caja_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimientos_caja_pago
        FOREIGN KEY (id_pago)
        REFERENCES pagos(id_pago)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_movimientos_caja_tipo
        CHECK
        (
            tipo_movimiento IN
            (
                'APERTURA',
                'VENTA',
                'INGRESO',
                'EGRESO',
                'DEVOLUCION',
                'AJUSTE',
                'CIERRE'
            )
        ),

    CONSTRAINT ck_movimientos_caja_monto
        CHECK (monto > 0)
);


CREATE INDEX IF NOT EXISTS
    ix_cajas_id_sucursal
ON cajas(id_sucursal);


CREATE INDEX IF NOT EXISTS
    ix_cajas_fecha_apertura
ON cajas(fecha_apertura DESC);


CREATE INDEX IF NOT EXISTS
    ix_cajas_estado
ON cajas(estado);


CREATE INDEX IF NOT EXISTS
    ix_movimientos_caja_id_caja
ON movimientos_caja
(
    id_caja,
    fecha_creacion
);


CREATE INDEX IF NOT EXISTS
    ix_movimientos_caja_id_pago
ON movimientos_caja(id_pago);


CREATE INDEX IF NOT EXISTS
    ix_movimientos_caja_tipo
ON movimientos_caja(tipo_movimiento);


COMMENT ON TABLE cajas IS
    'Aperturas y cierres de caja por sucursal.';

COMMENT ON TABLE movimientos_caja IS
    'Ingresos, egresos, ventas, devoluciones y ajustes de caja.';